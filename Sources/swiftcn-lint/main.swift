import Foundation
import SwiftCNLint

// swiftcn-lint [paths…] [--config file] [--format xcode|json] [--output file] [--reference]
//
// Checks swiftcn class strings in Swift sources with the swiftcn parser. Paths can be files or
// directories. Prints one diagnostic per line in the form Xcode shows inline, and exits with 1
// when it finds errors. The build plugin passes --output, a Swift file it writes on success.

let usage = """
usage: swiftcn-lint [paths…] [--config swiftcn-lint.json] [--format xcode|json] [--warnings] [--reference]

  paths        Swift files or directories to check (default: current directory)
  --config     Names registered at runtime: {"classes": [], "prefixes": [], "animations": []}
  --format     xcode (default) prints path:line:column: error: message; json prints an array
  --warnings   Report problems as warnings and exit successfully
  --reference  Print the Markdown reference of every swiftcn class and exit

"""

var paths: [String] = []
var configPath: String?
var format = "xcode"
var outputPath: String?
var warningsOnly = false
var arguments = CommandLine.arguments.dropFirst().makeIterator()
while let argument = arguments.next() {
    switch argument {
    case "--config": configPath = arguments.next()
    case "--format": format = arguments.next() ?? format
    case "--output": outputPath = arguments.next()
    case "--warnings": warningsOnly = true
    case "--reference":
        print(ClassReference.markdown(), terminator: "")
        exit(0)
    case "-h", "--help":
        print(usage, terminator: "")
        exit(0)
    default:
        if argument.hasPrefix("-") {
            FileHandle.standardError.write(Data("swiftcn-lint: unknown option \(argument)\n\n\(usage)".utf8))
            exit(2)
        }
        paths.append(argument)
    }
}
if paths.isEmpty { paths = ["."] }

var configuration = LintConfiguration()
if let configPath {
    do {
        configuration = try JSONDecoder().decode(LintConfiguration.self, from: Data(contentsOf: URL(fileURLWithPath: configPath)))
    } catch {
        FileHandle.standardError.write(Data("swiftcn-lint: could not read \(configPath): \(error)\n".utf8))
        exit(2)
    }
}
if warningsOnly { configuration.warningsOnly = true }

/// Swift files under the given paths, skipping build products and hidden directories.
func swiftFiles(_ paths: [String]) -> [String] {
    var files: [String] = []
    let manager = FileManager.default
    for path in paths {
        var isDirectory: ObjCBool = false
        guard manager.fileExists(atPath: path, isDirectory: &isDirectory) else {
            FileHandle.standardError.write(Data("swiftcn-lint: no such file or directory: \(path)\n".utf8))
            continue
        }
        guard isDirectory.boolValue else {
            if path.hasSuffix(".swift") { files.append(path) }
            continue
        }
        let skipped: Set<String> = [".build", "DerivedData", "node_modules", ".swiftpm", "Pods", "Carthage"]
        guard let enumerator = manager.enumerator(atPath: path) else { continue }
        while let relative = enumerator.nextObject() as? String {
            let name = (relative as NSString).lastPathComponent
            if name.hasPrefix(".") || skipped.contains(name) {
                if (enumerator.fileAttributes?[.type] as? FileAttributeType) == .typeDirectory { enumerator.skipDescendants() }
                continue
            }
            if relative.hasSuffix(".swift") { files.append((path as NSString).appendingPathComponent(relative)) }
        }
    }
    return files.sorted()
}

let files = swiftFiles(paths)
var sources: [(path: String, text: String)] = []
for file in files {
    if let text = try? String(contentsOfFile: file, encoding: .utf8) { sources.append((file, text)) }
}

var linter = SwiftCNLinter(configuration: configuration)
for source in sources { linter.learn(from: source.text) }
let diagnostics = sources.flatMap { linter.lint(source: $0.text, path: $0.path) }

switch format {
case "json":
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    print(String(decoding: try encoder.encode(diagnostics), as: UTF8.self))
default:
    for diagnostic in diagnostics { print(diagnostic.xcodeFormatted) }
}

let errors = diagnostics.filter { $0.severity == .error }.count
if errors > 0 {
    if format != "json" {
        FileHandle.standardError.write(Data("swiftcn-lint: \(errors) invalid class\(errors == 1 ? "" : "es") in \(files.count) file\(files.count == 1 ? "" : "s").\n".utf8))
    }
    exit(1)
}
if let outputPath {
    // The build plugin compiles this file; writing it marks the check as current.
    let stamp = "// Generated by swiftcn-lint: \(files.count) file\(files.count == 1 ? "" : "s") checked.\n"
    try? stamp.write(toFile: outputPath, atomically: true, encoding: .utf8)
}
