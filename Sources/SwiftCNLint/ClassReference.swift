@_spi(Tooling) import SwiftCN

/// A Markdown reference of every swiftcn class, generated from the parser's own tables.
/// The documentation site publishes it for people and coding agents.
public enum ClassReference {
    public static func markdown() -> String {
        let catalog = TWClassCatalog.self
        func list(_ names: [String]) -> String { names.map { "`\($0)`" }.joined(separator: " ") }
        func prefixed(_ prefix: String, _ names: [String]) -> String { list(names.map { prefix + $0 }) }
        let examples = catalog.argumentExamples.map { entry in
            "| `\(entry.prefix)-[…]` | " + (entry.example.map { "`\($0)`" } ?? "`\(entry.prefix)-[\\(value)]` (interpolated native value only)") + " |"
        }

        return """
        # swiftcn class reference

        <!-- Generated by `swift run swiftcn-lint --reference`. Do not edit by hand. -->

        Every class that swiftcn's parser accepts with the standard theme and default rules.
        Apply classes with `.tw("…")` on a view, `.buttonStyle(.tw("…"))` on a button, or the typed
        equivalents such as `.tw(.p(4), .bg(.surface))`. Later classes replace earlier ones by property
        within one `.tw` call. Unknown classes leave the whole surface unstyled at run time, and
        `swiftcn-lint` reports them at build time.

        Classes are not Tailwind's full set. Only the names below are valid; there are no responsive
        breakpoints, flex or grid utilities, percentages, `rem`, `calc`, or CSS variables.

        ## Variants

        Prefix a class with `variant:`. Combine variants, as in `disabled:hover:opacity-20`.

        \(prefixed("", catalog.variants.map { $0 + ":" }))

        Group variants accept a group name: `group-hover/hero:opacity-70`.

        ## Spacing and size

        \(catalog.families.prefix(2).map { "- `\($0.pattern)`: \($0.summary) Examples: \(list($0.examples))." }.joined(separator: "\n"))
        - `w-full`: fill the available width.
        - `h-full`: fill the available height.

        ## Typography

        - Sizes (scalable Dynamic Type styles): \(prefixed("text-", catalog.fontSizes))
        - Weights: \(prefixed("font-", catalog.weights))
        - Alignment: `text-start` `text-center` `text-end`
        - Line limits: `line-clamp-{n}`, `line-clamp-none`

        ## Color

        Theme colors, usable with `text-`, `bg-`, `border-`, `tint-`, and `glass-tint-`:

        \(list(catalog.colors))

        For example `text-muted-foreground`, `bg-surface`, `border-input`, `tint-primary`.
        Arbitrary colors use brackets: `bg-[#6366f1]`, `text-[#fff]`, `border-[color:#6366f180]`.

        ## Borders, corners, and shadows

        - Borders: `border` (1 point, theme border color), `border-{n}` (width in points), `border-{color}`
        - Corners: `rounded` (md), \(prefixed("rounded-", catalog.radii))
        - Shadows: `shadow` (sm), \(prefixed("shadow-", catalog.shadows))
        - Opacity: `opacity-{0…100}`

        ## Surfaces and Liquid Glass

        \(list(catalog.surfaces))

        `surface-floating` is Liquid Glass on iOS 26 and macOS 26, a material on earlier systems, and solid
        under Reduce Transparency. `bg-*` sets the color of a solid surface; it never stacks under glass.

        ## Native buttons and controls

        Use with `.buttonStyle(.tw("…"))`. Apple draws the button.

        - Recipes: `button-primary` `button-secondary` `button-outline` `button-destructive` `button-ghost` `button-link`
        - Styles: \(list(catalog.bezels)) `glass` `glass-prominent`
        - Size: \(list(catalog.controlSizes))
        - Tint: `tint-{color}` or `tint-[#hex]`

        ## Animation

        - Presets: \(prefixed("animate-", catalog.animationPresets))
        - Timing: `duration-{ms}` `delay-{ms}` (default duration 300)

        ## Groups and shared elements

        - `group`, `group/{name}`
        - `shared-[{id}]`, `shared-[{id}]/{group}`
        - \(list(catalog.sharedElements))

        ## Arbitrary values

        Brackets take native units: bare lengths are points, bare times are milliseconds, bare angles are
        degrees. Underscores stand for spaces. Interpolation keeps native Swift values: `rotate-[\\(angle)]`.

        | Prefix | Example |
        | --- | --- |
        \(examples.joined(separator: "\n"))

        ## Recipes

        Named classes that components use. Redefine them with `TWGlobalRules(named:)` or `.twRules { $0.named["card"] = "…" }`.

        \(list(catalog.recipes))

        ## Custom classes

        Register your own with `TWGlobalRules`: `named` for recipes, `utilities` and `modifiers` for
        custom classes and argument prefixes, and `animations` for presets. `swiftcn-lint` learns names
        registered in source; list others in `swiftcn-lint.json`.

        """
    }
}
